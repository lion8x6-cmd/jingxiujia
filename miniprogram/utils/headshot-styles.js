// ============ 导出 ============

module.exports = {
  IDENTITY_LOCK,
  POSE_FIX,
  QUALITY_RULES,
  BANNED,
  BEAUTY_LEVELS,
  STYLES,
  /**
   * 组装完整的职业照提示词
   * @param {string} styleId - 风格ID
   * @param {string} beautyLevel - 'off' | 'light' | 'medium'
   * @param {string} extraNotes - 额外要求
   * @returns {string}
   */
  buildHeadshotPrompt(styleId, beautyLevel, extraNotes) {
    const style = STYLES.find(s => s.id === styleId);
    if (!style) return '';
    const beauty = BEAUTY_LEVELS[beautyLevel] || BEAUTY_LEVELS.light;
    let prompt = style.prompt;
    prompt += '\n\n' + IDENTITY_LOCK;
    prompt += '\n' + POSE_FIX;
    prompt += '\n\n【美颜档位：' + beauty.name + '】\n' + beauty.prompt;
    prompt += '\n' + QUALITY_RULES;
    if (extraNotes && extraNotes.trim()) {
      prompt += '\n【额外要求】' + extraNotes.trim();
    }
    return prompt;
  }
};
